def _strip_blobs(data: Any) -> Any:
    """Remove unstable generated values before snapshot comparison.

    PNG bytes are generated by Pillow and differ across Python/Pillow versions,
    making exact blob comparison unreliable in CI environments.
    """
    if isinstance(data, dict):
        return {
            k: _strip_blobs("<test-runtime-public-key>" if k == "accessTokenPublicKey" else v)
            for k, v in data.items()
            if k != 'blob'
        }
    if isinstance(data, list):
        return [_strip_blobs(item) for item in data]
    return data



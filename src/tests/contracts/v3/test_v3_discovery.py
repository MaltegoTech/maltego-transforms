@pytest.mark.asyncio
async def test_web_client_includes_coalesce_entities(
    async_client_example_server: httpx.AsyncClient
) -> None:
    """Web client should receive entities with original coalesce in field default_value."""
    # Request with web client headers (include compositeEntities capability)
    headers = {**GRAPH_BROWSER_3_0_0, "maltego-client-capabilities": "compositeEntities"}
    response = await async_client_example_server.get(
        "/api/v3/assets/entities",
        headers=headers
    )
    assert response.status_code == 200

    entities = response.json()

    # Find AtomicCoalesceTestEntity - web client should get ORIGINAL coalesce in field
    atomic_entity = next(
        (e for e in entities if e["id"] == "maltego.AtomicCoalesceTestEntity"),
        None
    )
    assert atomic_entity is not None, \
        "Web client should receive atomic coalesce entities"
    # Web client gets original coalesce (no override for web)
    fields = atomic_entity.get("properties", {}).get("fields", [])
    display_field = next((f for f in fields if f.get("name") == "display_property"), None)
    assert display_field is not None, "display_property field should exist"
    assert "$coalesce(" in str(display_field.get("defaultValue", "")), \
        "Web client should receive original coalesce in field default_value"

    # Find CompositeCoalesceTestEntity - web client should get original coalesce in field
    composite_entity = next(
        (e for e in entities if e["id"] == "maltego.CompositeCoalesceTestEntity"),
        None
    )
    assert composite_entity is not None, \
        "Web client should receive composite coalesce entities"
    composite_fields = composite_entity.get("properties", {}).get("fields", [])
    composite_display_field = next((f for f in composite_fields if f.get("name") == "display_property"), None)
    assert composite_display_field is not None, "display_property field should exist"
    assert "$coalesce(" in str(composite_display_field.get("defaultValue", "")), \
        "Web client should receive original coalesce in field default_value for composite"

@pytest.mark.asyncio
async def test_layer1_override_removes_coalesce_layer2_allows(
    async_client_example_server: httpx.AsyncClient
) -> None:
    """
    Test Layer 1 + Layer 2 interaction:
    CoalescingDisplayPropertyEntity originally has $coalesce() in field default_value,
    but the override changes it to "$property(name)" (no coalesce).
    Layer 2 should NOT skip it because after override, it no longer has coalesce.
    """
    # Request with older desktop user agent (4.10.0)
    response = await async_client_example_server.get(
        "/api/v3/assets/entities",
        headers=UA_4_10_0
    )
    assert response.status_code == 200

    entities = response.json()

    # Find CoalescingDisplayPropertyEntity - should be included because override removed coalesce
    entity = next(
        (e for e in entities if e["id"] == "maltego.CoalescingDisplayPropertyEntity"),
        None
    )
    assert entity is not None, \
        "CoalescingDisplayPropertyEntity should be included because override removed coalesce"

    # Verify the field's default_value was changed from coalesce to simple "$property(name)"
    fields = entity.get("properties", {}).get("fields", [])
    display_field = next((f for f in fields if f.get("name") == "display_property"), None)
    assert display_field is not None, "display_property field should exist"
    assert display_field.get("defaultValue") == "$property(name)", \
        "Override should have changed field default_value from coalesce"


